const skillExecutors: Record<string, (inputs: Record<string, string>) => AgentRunResult> = {
  'draft-server-doc': runServerDoc,
  'gap-analysis': runGapAnalysis,
  'network-topology-doc': runNetworkDoc,
  'backup-procedure': runBackupProcedure,
  'security-audit-checklist': runSecurityChecklist,
  'incident-runbook': runIncidentRunbook,
};

export async function runAgentSkill(input: AgentRunInput): Promise<AgentRunResult> {
  const start = Date.now();
  const skill = getSkillById(input.skillId);

  if (!skill) {
    throw new Error(`Unknown skill: ${input.skillId}`);
  }

  for (const field of skill.fields) {
    if (field.required && !input.inputs[field.key]?.trim()) {
      throw new Error(`Required field missing: ${field.label}`);
    }
  }

  const executor = skillExecutors[input.skillId];
  if (!executor) {
    throw new Error(`Skill executor not implemented: ${input.skillId}`);
  }

  const result = executor(input.inputs);
  result.metadata.durationMs = Date.now() - start;
  return result;
}

