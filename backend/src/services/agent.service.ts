import { getSkillById, agentSkills } from '../skills/skillDefinitions.js';

export interface AgentRunInput {
  skillId: string;
  inputs: Record<string, string>;
  tenantId?: string;
}

export interface AgentFinding {
  severity: 'critical' | 'high' | 'medium' | 'low' | 'info';
  section: string;
  message: string;
  recommendation: string;
}

export interface AgentRunResult {
  skillId: string;
  skillName: string;
  status: 'completed' | 'failed';
  outputType: string;
  title: string;
  content: string;
  findings?: AgentFinding[];
  checklist?: { item: string; status: 'pass' | 'fail' | 'review'; notes: string }[];
  metadata: {
    executedAt: string;
    durationMs: number;
    sectionsGenerated: number;
  };
}

const NIST_800_123_REQUIRED = [
  { section: 'Basis-Informationen', keywords: ['hostname', 'ip', 'standort', 'verantwortlich'] },
  { section: 'Hardware', keywords: ['cpu', 'ram', 'speicher', 'hardware'] },
  { section: 'Software', keywords: ['betriebssystem', 'os', 'version', 'patch', 'software'] },
  { section: 'Dienste', keywords: ['dienst', 'service', 'port', 'rolle'] },
  { section: 'Netzwerk', keywords: ['netzwerk', 'vlan', 'subnet', 'gateway', 'dns'] },
  { section: 'Sicherheit', keywords: ['firewall', 'sicherheit', 'security', 'zugriff', 'verschlüsselung'] },
  { section: 'Backup', keywords: ['backup', 'wiederherstellung', 'recovery', 'rto', 'rpo'] },
  { section: 'Monitoring', keywords: ['monitoring', 'alert', 'überwachung', 'log'] },
];

function runGapAnalysis(inputs: Record<string, string>): AgentRunResult {
  const content = (inputs.documentContent || '').toLowerCase();
  const findings: AgentFinding[] = [];

  for (const req of NIST_800_123_REQUIRED) {
    const found = req.keywords.some((kw) => content.includes(kw));
    if (!found) {
      findings.push({
        severity: req.section === 'Sicherheit' || req.section === 'Backup' ? 'high' : 'medium',
        section: req.section,
        message: `Missing or insufficient coverage of "${req.section}"`,
        recommendation: `Add a dedicated section covering ${req.section.toLowerCase()} with required details per ${inputs.standard || 'NIST SP 800-123'}.`,
      });
    }
  }

  const coverage = Math.round(((NIST_800_123_REQUIRED.length - findings.length) / NIST_800_123_REQUIRED.length) * 100);

  return {
    skillId: 'gap-analysis',
    skillName: 'Documentation Gap Analysis',
    status: 'completed',
    outputType: 'findings',
    title: `Gap Analysis: ${inputs.documentTitle}`,
    content: `## Gap Analysis Report\n\n**Document:** ${inputs.documentTitle}\n**Standard:** ${inputs.standard}\n**Coverage Score:** ${coverage}%\n\n${findings.length === 0 ? '✅ No critical gaps found. Documentation meets standard requirements.' : `⚠️ ${findings.length} gap(s) identified.`}`,
    findings,
    metadata: { executedAt: new Date().toISOString(), durationMs: 0, sectionsGenerated: findings.length },
  };
}

